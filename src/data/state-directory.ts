export function getStateDetailBySlug(slug: string): IndianStateDetail | null {
  const clean = slug.toLowerCase().replace(/[^a-z0-9-]/g, "")
  if (INDIAN_STATES_DATA[clean]) return INDIAN_STATES_DATA[clean]
  
  // Try matching stateName
  const found = Object.values(INDIAN_STATES_DATA).find(
    (s) => s.stateSlug.toLowerCase() === clean || s.stateName.toLowerCase().replace(/\s+/g, "-") === clean
  )
  return found || null
}

export function getAllAvailableStateDetails(): IndianStateDetail[] {
  return Object.values(INDIAN_STATES_DATA)
}
